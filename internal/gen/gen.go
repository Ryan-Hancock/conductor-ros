// Package gen emits deployment artifacts from a validated graph: a ROS 2
// launch file (one process per node, using the app binary's -node flag), a
// ROS-style parameter file, and a Graphviz view of the topic graph.
package gen

import (
	"fmt"
	"os"
	"path/filepath"
	"strconv"
	"strings"

	"conductor.dev/conductor/internal/graph"
)

const header = "Generated by conductor from the application graph. DO NOT EDIT."

// LaunchXML renders a ROS 2 XML launch file that starts one process per
// node, listed in the bringup order derived from the application graph so
// providers start before the nodes that consume them.
func LaunchXML(g *graph.Graph, binPath string) string {
	order, cycles := g.BringupOrder()
	byName := map[string]bool{}
	for _, n := range g.App.Nodes {
		byName[n.Name] = true
	}

	var b strings.Builder
	fmt.Fprintf(&b, "<!-- %s -->\n", header)
	fmt.Fprintf(&b, "<!-- Nodes are listed in dependency order: %s -->\n", strings.Join(order, " -> "))
	if len(cycles) > 0 {
		fmt.Fprintf(&b, "<!-- Dependency cycle among %s; these start in declaration order. -->\n", strings.Join(cycles, ", "))
	}
	b.WriteString("<launch>\n")
	for _, name := range order {
		if !byName[name] {
			continue
		}
		fmt.Fprintf(&b, "  <executable cmd=%q name=%q output=\"screen\"/>\n",
			fmt.Sprintf("%s -node %s", binPath, name), name)
	}
	b.WriteString("</launch>\n")
	return b.String()
}

// ParamsYAML renders node parameters in ros2 param file layout. The result
// is a working parameter file: pass it back with `-params`, or copy it to
// params.<env>.yaml and edit it as an environment overlay.
func ParamsYAML(g *graph.Graph) string {
	var b strings.Builder
	fmt.Fprintf(&b, "# %s\n", header)
	fmt.Fprintf(&b, "# Load with: %s -params params.yaml\n", g.App.Name)
	wrote := false
	for _, n := range g.App.Nodes {
		if len(n.Params) == 0 {
			continue
		}
		wrote = true
		fmt.Fprintf(&b, "%s:\n  ros__parameters:\n", n.Name)
		for _, p := range n.Params {
			val := p.Default
			if val == "" {
				fmt.Fprintf(&b, "    # %s: <no default; %s>\n", p.Name, p.GoType)
				continue
			}
			if p.GoType == "string" || p.GoType == "time.Duration" {
				val = strconv.Quote(val)
			}
			fmt.Fprintf(&b, "    %s: %s\n", p.Name, val)
		}
	}
	if !wrote {
		b.WriteString("# (no parameters declared)\n")
	}
	return b.String()
}

// Dot renders the topic graph in Graphviz dot form: nodes as boxes, external
// endpoints dashed, topics as ellipses labeled with their ROS interface.
func Dot(g *graph.Graph) string {
	var b strings.Builder
	fmt.Fprintf(&b, "// %s\ndigraph %q {\n  rankdir=LR;\n  node [fontname=\"Helvetica\"];\n", header, g.App.Name)
	for _, n := range g.App.Nodes {
		fmt.Fprintf(&b, "  %q [shape=box];\n", n.Name)
	}
	hasExternal := false
	for _, t := range g.Topics {
		label := t.Name
		if rt := t.RosType(); rt != "" {
			label += `\n` + rt
		}
		// Hand-quoted: %q would escape the \n that Graphviz needs verbatim.
		fmt.Fprintf(&b, "  \"topic:%s\" [label=\"%s\", shape=ellipse, fontsize=10];\n", t.Name, label)
		for _, p := range t.Pubs {
			hasExternal = hasExternal || p.External
			fmt.Fprintf(&b, "  %q -> %q;\n", p.Node, "topic:"+t.Name)
		}
		for _, s := range t.Subs {
			hasExternal = hasExternal || s.External
			fmt.Fprintf(&b, "  %q -> %q;\n", "topic:"+t.Name, s.Node)
		}
	}
	if hasExternal {
		fmt.Fprintf(&b, "  %q [shape=box, style=dashed];\n", "(external)")
	}
	b.WriteString("}\n")
	return b.String()
}

// WriteAll writes every artifact under <app dir>/gen and returns the paths.
func WriteAll(g *graph.Graph, binPath string) ([]string, error) {
	outDir := filepath.Join(g.App.Dir, "gen")
	if err := os.MkdirAll(outDir, 0o755); err != nil {
		return nil, err
	}
	artifacts := map[string]string{
		g.App.Name + ".launch.xml": LaunchXML(g, binPath),
		"params.yaml":              ParamsYAML(g),
		"graph.dot":                Dot(g),
	}
	var written []string
	for name, content := range artifacts {
		p := filepath.Join(outDir, name)
		if err := os.WriteFile(p, []byte(content), 0o644); err != nil {
			return nil, err
		}
		written = append(written, p)
	}
	return written, nil
}
